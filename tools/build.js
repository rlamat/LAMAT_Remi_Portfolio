#!/usr/bin/env node
// Builds the static parts of the site. No dependencies: `node tools/build.js`.
//
// 1. Inlines the icon sprite (img/icons.svg) into the French pages, between the
//    <!-- icons:start --> / <!-- icons:end --> markers, so <use href="#i-…"> works
//    everywhere (including when a page is opened straight from the disk).
// 2. Generates the English pages in en/ from the French ones and i18n/en.json:
//    - data-i18n="key"            -> the element's inner HTML is replaced
//    - data-i18n-attr="attr:key;…" -> the listed attributes are replaced
//    - relative asset paths get a "../" prefix (en/ is one level deeper)
//    The build fails if a key used in a page has no English translation.

"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PAGES = ["index.html", "extramus.html"];
const ASSET_PREFIXES = ["img/", "pdf/", "styles/", "app.js"];

const read = f => fs.readFileSync(path.join(ROOT, f), "utf8");
const write = (f, s) => {
    fs.mkdirSync(path.dirname(path.join(ROOT, f)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, f), s);
};

// ---------- 1. Icon sprite ----------
function spriteMarkup() {
    const symbols = read("img/icons.svg").match(/<symbol[\s\S]*?<\/symbol>/g) || [];
    if (!symbols.length) throw new Error("img/icons.svg contains no <symbol>");
    return '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" width="0" height="0" style="position:absolute">\n'
        + symbols.map(s => "        " + s).join("\n") + "\n    </svg>";
}

function inlineSprite(html, sprite) {
    const re = /(<!-- icons:start -->)[\s\S]*?(<!-- icons:end -->)/;
    if (!re.test(html)) throw new Error("icons markers not found");
    return html.replace(re, `$1\n    ${sprite}\n    $2`);
}

// ---------- 2. English pages ----------
const escapeAttr = v => String(v).replace(/"/g, "&quot;");

function translate(html, en, page, missing) {
    const need = key => {
        if (!(key in en)) missing.add(`${page}: ${key}`);
        return en[key];
    };

    // Inner HTML of elements carrying data-i18n
    html = html.replace(
        /<([a-z0-9]+)([^>]*?)\sdata-i18n="([^"]+)"([^>]*)>([\s\S]*?)<\/\1>/g,
        (all, tag, before, key, after, inner) => {
            if (new RegExp(`<${tag}[\\s>]`).test(inner)) {
                throw new Error(`${page}: nested <${tag}> inside data-i18n="${key}" is not supported`);
            }
            const value = need(key);
            return `<${tag}${before}${after}>${value === undefined ? inner : value}</${tag}>`;
        }
    );

    // Attributes listed in data-i18n-attr
    html = html.replace(/<[a-z0-9]+[^>]*\sdata-i18n-attr="([^"]+)"[^>]*>/g, (tagHtml, spec) => {
        let out = tagHtml.replace(/\sdata-i18n-attr="[^"]*"/, "");
        for (const pair of spec.split(";")) {
            const [attr, key] = pair.split(":").map(s => s.trim());
            const value = need(key);
            if (value === undefined) continue;
            const attrRe = new RegExp(`(\\s${attr}=")[^"]*(")`);
            out = attrRe.test(out)
                ? out.replace(attrRe, `$1${escapeAttr(value)}$2`)
                : out.replace(/^(<[a-z0-9]+)/, `$1 ${attr}="${escapeAttr(value)}"`);
        }
        return out;
    });

    // en/ is one directory deeper: fix relative asset paths
    html = html.replace(/(\s(?:src|href|data-full)=")([^"]+)"/g, (all, start, url) =>
        ASSET_PREFIXES.some(p => url.startsWith(p)) ? `${start}../${url}"` : all
    );

    html = html.replace('<html lang="fr">', '<html lang="en">');
    return html.replace("<!DOCTYPE html>",
        "<!DOCTYPE html>\n<!-- Generated by tools/build.js from ../" + page + " and i18n/en.json. Do not edit by hand. -->");
}

function main() {
    const en = JSON.parse(read("i18n/en.json"));
    const sprite = spriteMarkup();
    const missing = new Set();
    const usedKeys = new Set();

    for (const page of PAGES) {
        const fr = inlineSprite(read(page), sprite);
        write(page, fr);

        for (const m of fr.matchAll(/data-i18n="([^"]+)"/g)) usedKeys.add(m[1]);
        for (const m of fr.matchAll(/data-i18n-attr="([^"]+)"/g)) {
            m[1].split(";").forEach(p => usedKeys.add(p.split(":")[1].trim()));
        }
        write(path.join("en", page), translate(fr, en, page, missing));
        console.log(`built en/${page}`);
    }

    const unused = Object.keys(en).filter(k => !k.startsWith("_") && !usedKeys.has(k));
    if (unused.length) console.warn("warning: unused keys in i18n/en.json:", unused.join(", "));
    if (missing.size) {
        console.error("error: missing English translations:\n  " + [...missing].join("\n  "));
        process.exit(1);
    }
}

main();
